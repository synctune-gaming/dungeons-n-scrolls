test('gives useful gifts for free, claims return boosts, and saves preset-only conversation history', async ({ page, activate }) => {
  await enter(page, 'ashen-gate', { health: 50, mana: 10 })
  const before = await readSave(page)
  await openAdventurer(page, activate, 'Mosskeeper')
  await activate(page.getByRole('button', { name: 'Chat with Mosskeeper', exact: true }))
  await expect(page.getByRole('textbox')).toHaveCount(0)
  await expect(page.locator('textarea, [contenteditable="true"]')).toHaveCount(0)
  await expect(page.getByText('Simulated chat', { exact: true })).toBeVisible()
  await activate(page.getByRole('button', { name: 'Safe travels, adventurer.', exact: true }))
  await activate(page.getByRole('button', { name: 'Give trail ration', exact: true }))
  const given = await readSave(page)
  expect(given.game.player).toEqual(before.game.player)
  expect(given.social.boosts.mosskeeper.health).toBe(4)
  await activate(page.getByRole('button', { name: 'Claim trail ration from Mosskeeper', exact: true }))
  const claimed = await readSave(page)
  expect(claimed.game.player.health).toBe(54)
  expect(claimed.game.player.gold).toBe(before.game.player.gold)
  expect(claimed.game.rng).toBe(before.game.rng)
  expect(claimed.game.giftClaims).toEqual(['mosskeeper'])
  await page.reload()
  await openAdventurer(page, activate, 'Mosskeeper')
  await activate(page.getByRole('button', { name: 'Chat with Mosskeeper', exact: true }))
  const log = page.getByRole('log', { name: 'Conversation with Mosskeeper' })
  await expect(log.getByText('Safe travels, adventurer.', { exact: true })).toBeVisible()
  await expect(log.getByText('Claimed', { exact: true })).toBeVisible()
  await expect(page.getByRole('textbox')).toHaveCount(0)
})

