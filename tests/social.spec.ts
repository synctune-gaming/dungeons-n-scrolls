async function navigate(page: Page, activate: (target: Locator) => Promise<void>, name: 'Timeline' | 'Search' | 'Profile') {
  await activate(page.getByRole('navigation', { name: 'Primary navigation' }).getByRole('button', { name, exact: true }))
}

async function openAdventurer(page: Page, activate: (target: Locator) => Promise<void>, name: string) {
  await navigate(page, activate, 'Search')
  await activate(page.getByRole('button', { name: new RegExp(`^${name}\\b`) }))
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
}

test('customizes a live hero profile and retains it across reloads and a new run', async ({ page, activate }) => {
  await enter(page)
  await navigate(page, activate, 'Profile')
  await activate(page.getByRole('button', { name: 'Edit profile', exact: true }))
  await page.getByRole('textbox', { name: 'Adventurer name' }).fill('Lantern Finch')
  await page.getByRole('radio', { name: 'Helm', exact: true }).check()
  await page.getByRole('radio', { name: 'Aether', exact: true }).check()
  await activate(page.getByRole('button', { name: 'Save profile', exact: true }))
  await expect(page.getByRole('heading', { name: 'Lantern Finch', exact: true })).toBeVisible()
  const personalized = await readSave(page)
  expect(personalized.social.hero).toEqual({ name: 'Lantern Finch', appearance: { style: 'helm', palette: 'aether' } })
  await page.reload()
  await navigate(page, activate, 'Profile')
  await expect(page.getByRole('heading', { name: 'Lantern Finch', exact: true })).toBeVisible()
  await activate(page.getByRole('button', { name: 'Edit profile', exact: true }))
  await expect(page.getByRole('radio', { name: 'Helm', exact: true })).toBeChecked()
  await expect(page.getByRole('radio', { name: 'Aether', exact: true })).toBeChecked()
  await activate(page.getByRole('button', { name: 'Cancel profile edit', exact: true }))
  await activate(page.getByRole('button', { name: 'Choose a class for a new adventure', exact: true }))
  await page.getByRole('radio', { name: /Ironbound/ }).check()
  await activate(page.getByRole('button', { name: 'Begin a new adventure', exact: true }))
  const restarted = await readSave(page)
  expect(restarted.social.hero).toEqual(personalized.social.hero)
  expect(restarted.game.player.classId).toBe('ironbound')
  expect(restarted.game.deck).toHaveLength(12)
})

